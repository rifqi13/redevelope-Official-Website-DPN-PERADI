                    <p class="lead-text">
                        <i class="fas fa-quote-left text-gold me-2"></i>
                        Perhimpunan Advokat Indonesia (PERADI) lahir dari semangat persatuan dan keinginan kuat untuk mewujudkan profesi advokat yang terhormat, mandiri, dan profesional di Indonesia.
                    </p>

                    <!-- Bagian 1: Latar Belakang -->
                    <h2>Latar Belakang</h2>
                    <p>
                        Sebelum berdirinya PERADI, profesi advokat di Indonesia dijalankan oleh beberapa organisasi yang bergerak sendiri-sendiri. Kondisi ini menyebabkan kurangnya keseragaman dalam standar profesi, kode etik, dan pembinaan advokat. Hal ini menjadi keprihatinan bersama bagi para praktisi hukum di Indonesia.
                    </p>
                    <p>
                        Pada awal tahun 2000-an, muncul keinginan kuat dari berbagai organisasi advokat untuk bersatu dalam satu wadah. Keinginan ini didorong oleh kebutuhan akan <strong>profesi advokat yang terstandarisasi, berintegritas, dan memiliki satu kode etik yang berlaku secara nasional</strong>.
                    </p>

                    <div class="highlight-box">
                        <i class="fas fa-info-circle"></i>
                        <strong>Fakta Penting:</strong> Kesadaran akan pentingnya persatuan advokat di Indonesia semakin menguat seiring dengan tuntutan reformasi hukum dan kebutuhan akan penegakan hukum yang berkeadilan di era demokrasi.
                    </div>

                    <!-- Bagian 2: Pendirian -->
                    <h2>Pendirian PERADI</h2>
                    <p>
                        <strong>Perhimpunan Advokat Indonesia (PERADI)</strong> secara resmi didirikan pada tanggal <strong>23 Mei 2002</strong> melalui kesepakatan 7 organisasi advokat yang tergabung dalam <strong>Komite Kerja Advokat Indonesia (KKAI)</strong>.
                    </p>

                    <h3>Organisasi Pendiri PERADI</h3>
                    <div class="org-list">
                        <div class="org-item">
                            IKADIN
                            <span class="small">Ikatan Advokat Indonesia</span>
                        </div>
                        <div class="org-item">

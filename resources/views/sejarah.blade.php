                            <span class="small">Asosiasi Advokat Indonesia</span>
                        </div>
                        <div class="org-item">
                            IPHI
                            <span class="small">Ikatan Penasehat Hukum Indonesia</span>
                        </div>
                        <div class="org-item">
                            HAPI

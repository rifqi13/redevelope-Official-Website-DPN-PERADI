                        </div>
                        <div class="org-item">
                            SPI
                            <span class="small">Serikat Pengacara Indonesia</span>
                        </div>
                        <div class="org-item">
                            AKHI
                            <span class="small">Asosiasi Konsultan Hukum Indonesia</span>
                        </div>
                        <div class="org-item">
                            HKHPM
                            <span class="small">Himpunan Konsultan Hukum Pasar Modal</span>
                        </div>
                    </div>

                    <p>
                        Kesepakatan ini merupakan tonggak sejarah penting bagi profesi advokat di Indonesia. PERADI hadir sebagai <strong>wadah tunggal</strong> bagi para advokat untuk menjalankan profesi secara terhormat dan profesional, dengan satu kode etik yang mengikat seluruh anggotanya.
                    </p>

                    <!-- Bagian 3: Landasan Hukum -->
                    <h2>Landasan Hukum</h2>
                    <p>
                        Pada tanggal <strong>2 April 2003</strong>, Pemerintah Republik Indonesia mengesahkan <strong>Undang-Undang No. 18 Tahun 2003 tentang Advokat</strong>. UU ini menjadi landasan hukum utama bagi profesi advokat di Indonesia dan sekaligus mengakui keberadaan PERADI sebagai organisasi profesi advokat.
                    </p>

                    <div class="quote-block">
                        <p>
                            Advokat adalah profesi yang mulia dan terhormat (officium nobile), yang dalam menjalankan profesinya berada di bawah perlindungan hukum, undang-undang, dan kode etik.
                        </p>
                        <div class="quote-author">— Kode Etik Advokat Indonesia</div>
                    </div>

                    <p>
                        UU Advokat mengatur berbagai aspek penting, termasuk pengangkatan dan pemberhentian advokat, hak dan kewajiban advokat, organisasi profesi, serta pembentukan Dewan Kehormatan Advokat. Keberadaan UU ini semakin menguatkan posisi PERADI sebagai organisasi profesi yang sah dan diakui negara.
                    </p>

                    <!-- Bagian 4: Perkembangan -->
                    <h2>Perkembangan dan Penguatan Organisasi</h2>

                    <h3>2010-2015: Ekspansi dan Modernisasi</h3>
                    <p>
                        Pada periode ini, PERADI mulai memperkuat struktur organisasi dengan membentuk <strong>Dewan Pimpinan Nasional (DPN)</strong> di tingkat pusat dan <strong>Dewan Pimpinan Cabang (DPC)</strong> di berbagai daerah. Jumlah cabang berkembang pesat, mencerminkan tingginya kebutuhan akan advokat yang terorganisir di seluruh Indonesia.
                    </p>

                    <p>
                        Pada tahun <strong>2015</strong>, PERADI melakukan <strong>penyesuaian Anggaran Dasar dan Anggaran Rumah Tangga (AD/ART)</strong> untuk mengakomodasi perkembangan organisasi dan kebutuhan profesi di era modern. Beberapa perubahan penting meliputi:
                    </p>
                    <ul>
                        <li>Struktur organisasi yang lebih ramping dan efektif</li>
                        <li>Peningkatan standar kompetensi advokat melalui pendidikan berkelanjutan</li>
                        <li>Penguatan peran Dewan Kehormatan dalam mengawasi pelaksanaan kode etik</li>
                        <li>Digitalisasi administrasi keanggotaan</li>
                    </ul>

                    <!-- Bagian 5: Era Baru -->
                    <h2>Era Kepemimpinan Baru (2020-Sekarang)</h2>
                    <p>
                        Pada periode <strong>2020-2025</strong>, DPN PERADI dipimpin oleh <strong>Prof. Dr. Otto Hasibuan, S.H., M.M.</strong> sebagai Ketua Umum. Kepemimpinan ini membawa semangat perubahan dan penguatan profesi advokat di Indonesia.
                    </p>

                    <p>
                        Di bawah kepemimpinan ini, beberapa program prioritas dijalankan, antara lain:
                    </p>
                    <ul>
                        <li><strong>Penguatan Pusat Bantuan Hukum</strong> untuk memberikan akses keadilan bagi masyarakat kurang mampu</li>
                        <li><strong>Pengembangan Young Lawyers Committee</strong> sebagai wadah pengembangan advokat muda</li>
                        <li><strong>Pendidikan berkelanjutan</strong> bagi advokat untuk meningkatkan kompetensi</li>
                        <li><strong>Kerjasama internasional</strong> untuk memperluas wawasan dan jaringan profesi</li>
                    </ul>

                    <p>
                        Pada tahun <strong>2024</strong>, PERADI meresmikan <strong>PERADI Tower</strong> sebagai pusat kegiatan dan sekretariat nasional. Gedung ini menjadi simbol kebanggaan dan pusat pengembangan profesi advokat di Indonesia, dilengkapi dengan berbagai fasilitas modern untuk menunjang kegiatan organisasi.
                    </p>

                    <!-- Bagian 6: Visi Masa Depan -->
                    <h2>Visi dan Misi ke Depan</h2>
                    <div class="highlight-box" style="border-left-color: var(--primary-blue);">
                        <i class="fas fa-bullseye" style="color:var(--primary-blue);"></i>
                        <strong>Visi PERADI:</strong> Menjadi organisasi profesi advokat yang profesional, mandiri, dan terpercaya dalam menegakkan supremasi hukum dan keadilan di Indonesia.
                    </div>
                    <div class="highlight-box" style="border-left-color: var(--primary-blue);">
                        <i class="fas fa-flag" style="color:var(--primary-blue);"></i>
                        <strong>Misi PERADI:</strong>
                        <ul style="margin-top:8px; margin-bottom:0;">
                            <li>Meningkatkan kompetensi dan profesionalisme advokat melalui pendidikan berkelanjutan</li>
                            <li>Memperjuangkan hak-hak konstitusional masyarakat melalui bantuan hukum</li>
                            <li>Mengawal penegakan hukum yang berkeadilan di Indonesia</li>
                            <li>Membangun kemitraan strategis dengan lembaga hukum dan pemerintah</li>
                            <li>Mengembangkan advokat muda sebagai penerus profesi yang berintegritas</li>
                        </ul>
                    </div>


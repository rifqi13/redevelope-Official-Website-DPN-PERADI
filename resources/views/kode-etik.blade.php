                        <p style="text-align: justify;text-justify: inter-word;padding:10px;font-weight:normal;">Dengan demikian Kode Etik Advokat Indonesia adalah sebagai hukum tertinggi dalam menjalankan profesi, yang menjamin dan melindungi namun membebankan kewajiban kepada setiap Advokat untuk jujur dan bertanggung jawab dalam menjalankan profesinya baik kepada klien, pengadilan, negara atau masyarakat dan terutama kepada dirinya sendiri.</p>

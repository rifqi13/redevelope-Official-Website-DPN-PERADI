                        <p style="text-align: justify;text-justify: inter-word;padding:10px;font-weight:normal;">Advokat sebagai profesi terhormat (officium nobile) yang dalam menjalankan profesinya berada dibawah perlindungan hukum, undang-undang dan Kode Etik, memiliki kebebasan yang didasarkan kepada kehormatan dan kepribadian Advokat yang berpegang teguh kepada Kemandirian, Kejujuran, Kerahasiaan dan Keterbukaan. Bahwa profesi Advokat adalah selaku penegak hukum yang sejajar dengan instansi penegak hukum lainnya, oleh karena itu satu sama lainnya harus saling menghargai antara teman sejawat dan juga antara para penegak hukum lainnya.</p>

                            <li>Dewan Kehormatan berwenang memeriksa dan mengadili perkara pelanggaran Kode Etik  yang dilakukan oleh Advokat.</li>
                            <li>Pemeriksaan suatu pengaduan dapat dilakukan melalui dua tingkat, yaitu:
                                <ol style="text-align:justify;line-height:20px;margin-left:30px;" type="a">
                                    <li>Tingkat Dewan Kehormatan Cabang/Daerah.</li>
                                    <li>Tingkat Dewan Kehormatan Pusat.</li>
                                </ol>
                            </li>
                            <li>Dewan Kehormatan Cabang/daerah memeriksa pengaduan pada tingkat pertama dan Dewan Kehormatan Pusat pada tingkat terakhir.</li>
                            <li>Segala biaya yang dikeluarkan dibebankan kepada:
                                <ol style="text-align:justify;line-height:20px;margin-left:30px;" type="a">
                                    <li>Dewan Pimpinan Cabang/Daerah dimana teradu sebagai anggota pada tingkat Dewan Kehormatan Cabang/Daerah;</li>
                                    <li>Dewan Pimpinan Pusat pada tingkat Dewan Kehormatan Pusat organisasi dimana teradu sebagai anggota;</li>
                                    <li>Pengadu/Teradu.</li>
                                </ol>
                            </li>
                            </ol>

                            <h4 class="fw-bold" style="font-size:1.1rem;text-align:center;">Bagian Kedua<br>
                            PENGADUAN</h4>
                            <h4 class="fw-bold" style="font-size:1.1rem; color:var(--primary-blue);">Pasal 11</h4>
                            <ol style="text-align:justify;line-height:20px;margin-left:30px;" type="1">
                            <li>Pengaduan dapat diajukan oleh pihak-pihak yang berkepentingan dan merasa dirugikan, yaitu:
                                <ol style="text-align:justify;line-height:20px;margin-left:30px;" type="a">
                                    <li>Klien.</li>
                                    <li>Teman sejawat Advokat.</li>
                                    <li>Pejabat Pemerintah.</li>
                                    <li>Anggota Masyarakat.</li>
                                    <li>Dewan Pimpinan Pusat/Cabang/Daerah dari organisasi profesi dimana Teradu menjadi anggota.</li>
                                </ol>
                            </li>
                            <li>Selain untuk kepentingan organisasi, Dewan Pimpinan Pusat atau Dewan Pimpinan Cabang/Daerah dapat juga bertindak sebagai pengadu dalam hal yang menyangkut  epentingan hukum dan kepentingan umum dan yang dipersamakan untuk itu.</li>
                            <li>Pengaduan yang dapat diajukan hanyalah yang mengenai pelanggaran terhadap Kode Etik Advokat.</li>
                            </ol>

                            <h4 class="fw-bold" style="font-size:1.1rem;text-align:center;">Bagian Ketiga<br>
                            TATA CARA PENGADUAN</h4>
                            <h4 class="fw-bold" style="font-size:1.1rem; color:var(--primary-blue);">Pasal 12</h4>
                            <ol style="text-align:justify;line-height:20px;margin-left:30px;" type="1">
                            <li>Pengaduan terhadap Advokat sebagai teradu yang dianggap melanggar Kode Etik Advokat harus disampaikan secara tertulis disertai dengan alasan-alasannya kepada Dewan Kehormatan Cabang/Daerah atau kepada dewan Pimpinan Cabang/Daerah atau Dewan Pimpinan Pusat dimana teradu menjadi anggota.</li>
                            <li>Bilamana di suatu tempat tidak ada Cabang/Daerah Organisasi, pengaduan disampaikan kepada Dewan Kehormatan Cabang/Daerah terdekat atau Dewan Pimpinan Pusat.</li>
                            <li>Bilamana pengaduan disampaikan kepada Dewan Pimpinan Cabang/Daerah, maka Dewan Pimpinan Cabang/Daerah meneruskannya kepada Dewan Kehormatan Cabang/Daerah yang berwenang untuk memeriksa pengaduan itu.</li>
                            <li>Bilamana pengaduan disampaikan kepada Dewan Pimpinan Pusat/Dewan Kehormatan Pusat, maka Dewan Pimpinan Pusat/Dewan Kehormatan Pusat meneruskannya kepada Dewan Kehormatan Cabang/Daerah yang berwenang untuk memeriksa pengaduan itu baik langsung atau melalui Dewan Dewan Pimpinan Cabang/Daerah.</li>
                            </ol>

                            <h4 class="fw-bold" style="font-size:1.1rem;text-align:center;">Bagian Keempat<br>
                            PEMERIKSAAN TINGKAT PERTAMA OLEH DEWAN KEHORMATAN CABANG/DAERAH</h4>
                            <h4 class="fw-bold" style="font-size:1.1rem; color:var(--primary-blue);">Pasal 13</h4>
                            <ol style="text-align:justify;line-height:20px;margin-left:30px;" type="1">
                            <li>Dewan Kehormatan Cabang/Daerah setelah menerima pengaduan tertulis yang disertai surat-surat bukti yang dianggap perlu, menyampaikan surat pemberitahuan selambatlambatnya dalam waktu 14 (empat belas) hari dengan surat kilat khusus/tercatat kepada teradu tentang adanya pengaduan dengan menyampaikan salinan/copy surat pengaduan tersebut.</li>
                            <li>Selambat-lambatnya dalam waktu 21 (dua puluh satu) hari pihak teradu harus memberikan jawabannya secara tertulis kepada Dewan Kehormatan Cabang/Daerah yang bersangkutan, disertai surat-surat bukti yang dianggap perlu.</li>
                            <li>Jika dalam waktu 21 (dua puluh satu) hari tersebut teradu tidak memberikan jawaban tertulis, Dewan Kehormatan Cabang/Daerah menyampaikan pemberitahuan kedua dengan peringatan bahwa apabila dalam waktu 14 (empat belas) hari sejak tanggal surat peringatan tersebut ia tetap tidak memberikan jawaban tertulis, maka ia dianggap telah melepaskan hak jawabnya.</li>
                            <li>Dalam hal teradu tidak menyampaikan jawaban sebagaimana diatur di atas dan dianggap telah melepaskan hak jawabnya, Dewan Kehormatan Cabang/Daerah dapat segera menjatuhkan putusan tanpa kehadiran pihak-pihak yang bersangkutan.</li>
                            <li>Dalam hal jawaban yang diadukan telah diterima, maka Dewan Kehormatan dalam waktu selambat-lambatnya 14 (empat belas) hari menetapkan hari sidang dan menyampaikan panggilan secara patut kepada pengadu dan kepada teradu untuk hadir dipersidangan yang sudah ditetapkan tersebut.</li>
                            <li>Panggilan-panggilan tersebut harus sudah diterima oleh yang bersangkutan paling tambat 3 (tiga) hari sebelum hari sidang yang ditentukan.</li>
                            <li>Pengadu dan yang teradu:
                                <ol style="text-align:justify;line-height:20px;margin-left:30px;" type="a">
                                    <li>Harus hadir secara pribadi dan tidak dapat menguasakan kepada orang lain, yang jika dikehendaki masing-masing dapat didampingi oleh penasehat.</li>
                                    <li>Berhak untuk mengajukan saksi-saksi dan bukti-bukti.</li>
                                </ol>
                            </li>
                            <li>Pada sidang pertama yang dihadiri kedua belah pihak:
                                <ol style="text-align:justify;line-height:20px;margin-left:30px;" type="a">
                                    <li>Dewan Kehormatan akan menjelaskan tata cara pemeriksaan yang berlaku;</li>
                                    <li>Perdamaian hanya dimungkinkan bagi pengaduan yang bersifat perdata atau hanya untuk kepentingan pengadu dan teradu dan tidak mempunyai kaitan langsung dengan kepentingan organisasi atau umum, dimana pengadu akan mencabut kembali pengaduannya atau dibuatkan akta perdamaian yang dijadikan dasar keputusan oleh Dewan Kehormatan Cabang/Daerah yang langsung mempunyai kekuatan hukum yang pasti.</li>
                                    <li>Kedua belah pihak diminta mengemukakan alasan-alasan pengaduannya atau pembelaannya secara bergiliran, sedangkan surat-surat bukti akan diperiksa dan saksi-saksi akan didengar oleh Dewan Kehormatan Cabang/Daerah.</li>
                                </ol>
                            </li>
                            <li>Pada sidang pertama yang dihadiri kedua belah pihak:
                                <ol style="text-align:justify;line-height:20px;margin-left:30px;" type="a">
                                    <li>Dewan Kehormatan akan menjelaskan tata cara pemeriksaan yang berlaku;</li>
                                    <li>Perdamaian hanya dimungkinkan bagi pengaduan yang bersifat perdata atau hanya untuk kepentingan pengadu dan teradu dan tidak mempunyai kaitan langsung dengan kepentingan organisasi atau umum, dimana pengadu akan mencabut kembali pengaduannya atau dibuatkan akta perdamaian yang dijadikan dasar keputusan oleh Dewan Kehormatan Cabang/Daerah yang langsung mempunyai kekuatan hukum yang pasti.</li>
                                    <li>Kedua belah pihak diminta mengemukakan alasan-alasan pengaduannya atau pembelaannya secara bergiliran, sedangkan surat-surat bukti akan diperiksa dan saksi-saksi akan didengar oleh Dewan Kehormatan Cabang/Daerah.</li>
                                </ol>
                            </li>
                            </ol>

                            <h4 class="fw-bold" style="font-size:1.1rem;text-align:center;">Bagian Kelima<br>
                            SIDANG DEWAN KEHORMATAN CABANG/DAERAH</h4>
                            <h4 class="fw-bold" style="font-size:1.1rem; color:var(--primary-blue);">Pasal 14</h4>
                            <ol style="text-align:justify;line-height:20px;margin-left:30px;" type="1">
                                <li>Dewan Kehormatan Cabang/Daerah bersidang dengan Majelis yang terdiri sekurangkurangnya atas 3 (tiga) orang anggota yang salah satu merangkap sebagai Ketua Majelis, tetapi harus selalu berjumlah ganjil.</li>
                                <li>Majelis dapat terdiri dari Dewan Kehormatan atau ditambah dengan Anggota Majelis Kehormatan Ad Hoc yaitu orang yang menjalankan profesi dibidang hukum serta mempunyai pengetahuan dan menjiwai Kode Etik Advokat.</li>
                                <li>Majelis dipilih dalam rapat Dewan Kehormatan Cabang/Daerah yang khusus dilakukan untuk itu yang dipimpin oleh Ketua Dewan Kehormatan Cabang/Daerah atau jika ia berhalangan oleh anggota Dewan lainnya yang tertua,</li>
                                <li>Setiap dilakukan persidangan, Majelis Dewan Kehormatan diwajibkan membuat atau menyuruh membuat berita acara persidangan yang disahkan dan ditandatangani oleh Ketua Majelis yang menyidangkan perkara itu.</li>
                                <li>Sidang-sidang dilakukan secara tertutup, sedangkan keputusan diucapkan dalam sidang terbuka.</li>
                            </ol>

                            <h4 class="fw-bold" style="font-size:1.1rem;text-align:center;">Bagian Keenam<br>
                            CARA PENGAMBILAN KEPUTUSAN</h4>
                            <h4 class="fw-bold" style="font-size:1.1rem; color:var(--primary-blue);">Pasal 15</h4>
                            <ol style="text-align:justify;line-height:20px;margin-left:30px;" type="1">
                                <li>Setelah memeriksa dan mempertimbangkan pengaduan, pembelaan, surat-surat bukti dan keterangan saksi-saksi maka Majelis Dewan Kehormatan mengambil Keputusan yang dapat berupa:
                                    <ol style="text-align:justify;line-height:20px;margin-left:30px;" type="a">
                                        <li>Menyatakan pengaduan dari pengadu tidak dapat diterima;</li>
                                        <li>Menerima pengaduan dari pengadu dan mengadili serta menjatuhkan sanksisanksi kepada teradu;</li>
                                        <li>Menolak pengaduan dari pengadu.</li>
                                    </ol>
                                </li>
                                <li>Keputusan harus memuat pertimbangan-pertimbangan yang menjadi dasarnya dan menunjuk pada pasal-pasal Kode Etik yang dilanggar.</li>
                                <li>Majelis Dewan Kehormatan mengambil keputusan dengan suara terbanyak dan mengucapkannya dalam sidang terbuka dengan atau tanpa dihadiri oleh pihak-pihak yang bersangkutan, setelah sebelumnya memberitahukan hari, tanggal dan waktu persidangan tersebut kepada pihak-pihak yang bersangkutan.</li>
                                <li>Anggota Majelis yang kalah dalam pengambilan suara berhak membuat catatan keberatan yang dilampirkan didalam berkas perkara.</li>
                                <li>Keputusan ditandatangani oleh Ketua dan semua Anggota Majelis, yang apabila berhalangan untuk menandatangani keputusan, hal mana disebut dalam keputusan yang bersangkutan.</li>
                            </ol>

                            <h4 class="fw-bold" style="font-size:1.1rem;text-align:center;">Bagian Ketujuh<br>
                            SANKSI-SANKSI</h4>
                            <h4 class="fw-bold" style="font-size:1.1rem; color:var(--primary-blue);">Pasal 16</h4>
                            <ol style="text-align:justify;line-height:20px;margin-left:30px;" type="1">
                                <li>Hukuman yang diberikan dalam keputusan dapat berupa:
                                    <ol style="text-align:justify;line-height:20px;margin-left:30px;" type="a">
                                            <li>Peringatan biasa.</li>
                                            <li>Peringatan keras.</li>
                                            <li>Pemberhentian sementara untuk waktu tertentu.</li>
                                            <li>Pemecatan dari keanggotaan organisasi profesi.</li>
                                    </ol>
                                </li>
                                <li>Hukuman yang diberikan dalam keputusan dapat berupa:
                                    <ol style="text-align:justify;line-height:20px;margin-left:30px;" type="a">
                                            <li>Peringatan biasa bilamana sifat pelanggarannya tidak berat.</li>
                                            <li>Peringatan keras bilamana sifat pelanggarannya berat atau karena mengulangi kembali melanggar kode etik dan atau tidak mengindahkan sanksi peringatan yang pernah diberikan.</li>
                                            <li>Pemberhentian sementara untuk waktu tertentu bilamana sifat pelanggarannya berat, tidak mengindahkan dan tidak menghormati ketentuan kode etik atau bilamana setelah mendapat sanksi berupa peringatan keras masih mengulangi melakukan pelanggaran kode etik.</li>
                                            <li>Pemecatan dari keanggotaan organisasi profesi bilamana dilakukan pelanggaran kode etik dengan maksud dan tujuan merusak citra serta martabat kehormatan profesi Advokat yang wajib dijunjung tinggi sebagai profesi yang mulia dan terhormat.</li>
                                    </ol>
                                </li>
                                <li>Pemberian sanksi pemberhentian sementara untuk waktu tertentu harus diikuti larangan untuk menjalankan profesi advokat diluar maupun dimuka pengadilan.</li>
                                <li>Terhadap mereka yang dijatuhi sanksi pemberhentian sementara untuk waktu tertentu dan atau pemecatan dari keanggotaan organisasi profesi disampaikan kepada Mahkamah Agung untuk diketahui dan dicatat dalam daftar Advokat.</li>
                            </ol>

                            <h4 class="fw-bold" style="font-size:1.1rem;text-align:center;">Bagian Kedelapan<br>
                            PENYAMPAIAN SALINAN KEPUTUSAN</h4>
                            <h4 class="fw-bold" style="font-size:1.1rem; color:var(--primary-blue);">Pasal 17</h4>
                            <p style="text-align: justify;text-justify: inter-word;padding:10px;font-weight:normal;">Dalam waktu selambat-lambatnya 14 (empat belas) hari setelah keputusan diucapkan, salinan keputusan Dewan kehormatan Cabang/Daerah harus disampaikan kepada:</p>
                            <ol style="text-align:justify;line-height:20px;margin-left:30px;" type="a">
                                <li>Anggota yang diadukan/teradu;</li>
                                <li>Pengadu;</li>
                                <li>Dewan Pimpinan Cabang/Daerah dari semua organisasi profesi;</li>
                                <li>Dewan Pimpinan Pusat dari masing-masing organisasi profesi;</li>
                                <li>Dewan Kehormatan Pusat;</li>
                                <li>Instansi-instansi yang dianggap perlu apabila keputusan telah mempunyai kekuatan hukum yang pasti.</li>
                            </ol>

                            
                            <h4 class="fw-bold" style="font-size:1.1rem;text-align:center;">Bagian Kesembilan<br>
                            KEPUTUSAN DEWAN KEHORMATAN</h4>
                            <h4 class="fw-bold" style="font-size:1.1rem; color:var(--primary-blue);">Pasal 18</h4>
                            <ol style="text-align:justify;line-height:20px;margin-left:30px;" type="1">
                                <li>Apabila pengadu atau teradu tidak puas dengan keputusan Dewan Kehormatan Cabang/Daerah, ia berhak mengajukan permohonan banding atas keputusan tersebut kepada Dewan Kehormatan Pusat.</li>
                                <li>Pengajuan permohonan banding beserta Memori Banding yang sifatnya wajib, harus disampaikan melalui Dewan Kehormatan Cabang/Daerah dalam waktu 21 (dua puluh satu) hari sejak tanggal yang bersangkutan menerima salinan keputusan.</li>
                                <li>Dewan Kehormatan Cabang/Daerah setelah menerima Memori Banding yang bersangkutan selaku pembanding selambat-lambatnya dalam waktu 14 (empat belas) hari sejak penerimaannya, mengirimkan salinannya melalui surat kilat khusus/tercatat kepada pihak lainnya selaku terbanding.</li>
                                <li>Pihak terbanding dapat mengajukan Kontra Memori Banding selambat-lambatnya dalam waktu 21 (dua puluh satu) hari sejak penerimaan Memori Banding.</li>
                                <li>Jika jangka waktu yang ditentukan terbanding tidak menyampaikan Kontra Memori Banding ia dianggap telah melepaskan haknya untuk itu.</li>
                                <li>Selambat-lambatnya dalam waktu 14 (empat belas) hari sejak berkas perkara dilengkapi dengan bahan-bahan yang diperlukan, berkas perkara tersebut diteruskan oleh Dewan Kehormatan Cabang/Daerah kepada dewan Kehormatan Pusat.</li>
                                <li>Pengajuan permohonan banding menyebabkan ditundanya pelaksanaan keputusan Dewan Kehormatan Cabang/Daerah.</li>
                                <li>Dewan kehormatan Pusat memutus dengan susunan Majelis yang terdiri sekurangkurangnya 3 (tiga) orang anggota atau lebih tetapi harus berjumlah ganjil yang salah satu merangkap Ketua Majelis.</li>
                                <li>Majelis dapat terdiri dari Dewan Kehormatan atau ditambah dengan Anggota Majelis Kehormatan Ad Hoc yaitu orang yang menjalankan profesi dibidang hukum serta mempunyai pengetahuan dan menjiwai Kode Etik Advokat.</li>
                                <li>Majelis dipilih dalam rapat Dewan Kehormatan Pusat yang khusus diadakan untuk itu yang dipimpin oleh Ketua Dewan Kehormatan Pusat atau jika ia berhalangan oleh anggota Dewan lainnya yang tertua.</li>
                                <li>Dewan Kehormatan Pusat memutus berdasar bahan-bahan yang ada dalam berkas perkara, tetapi jika dianggap perlu dapat meminta bahan tambahan dari pihak-pihak yang bersangkutan atau memanggil mereka langsung atas biaya sendiri.</li>
                                <li>Dewan Kehormatan Pusat secara prorogasi dapat menerima permohonan pemeriksaan langsung dari suatu perkara yang diteruskan oleh Dewan Kehormatan Cabang/Daerah asal saja permohonan seperti itu dilampiri surat persetujuan dari kedua belah pihak agar perkaranya diperiksa langsung oleh Dewan Kehormatan Pusat.</li>
                                <li>Semua ketentuan yang berlaku untuk pemeriksaan pada tingkat pertama oleh Dewan Kehormatan Cabang/Daerah, mutatis mutandis berlaku untuk pemeriksaan pada tingkat banding oleh Dewan Kehormatan Pusat.</li>
                            </ol>

                            
                            <h4 class="fw-bold" style="font-size:1.1rem;text-align:center;">Bagian Kesepuluh<br>
                            KEPUTUSAN DEWAN KEHORMATAN</h4>
                            <h4 class="fw-bold" style="font-size:1.1rem; color:var(--primary-blue);">Pasal 19</h4>
                            <ol style="text-align:justify;line-height:20px;margin-left:30px;" type="1">
                                <li>Dewan Kehormatan Pusat dapat menguatkan, merubah atau membatalkan keputusan Dewan Kehormatan Cabang/Daerah dengan memutus sendiri.</li>
                                <li>Keputusan Dewan kehormatan Pusat mempunyai kekuatan tetap sejak diucapkan dalam sidang terbuka dengan atau tanpa dihadiri para pihak dimana hari, tanggal dan waktunya telah diberitahukan sebelumnya kepada pihak-pihak yang bersangkutan.</li>
                                <li>Keputusan Dewan Kehormatan Pusat adalah final dan mengikat yang tidak dapat diganggu gugat dalam forum manapun, termasuk dalam MUNAS.</li>
                                <li>Dalam waktu selambat-lambatnya 14 (empat belas) hari setelah keputusan diucapkan, salinan keputusan Dewan Kehormatan Pusat harus disampaikan kepada:
                                    <ol style="text-align:justify;line-height:20px;margin-left:30px;" type="a">
                                        <li>Anggota yang diadukan/teradu baik sebagai pembanding ataupun terbanding;</li>
                                        <li>Pengadu baik selaku pembanding ataupun terbanding;</li>
                                        <li>Dewan Pimpinan Cabang/Daerah yang bersangkutan;</li>
                                        <li>Dewan Kehormatan Cabang/Daerah yang bersangkutan;</li>
                                        <li>Dewan Pimpinan Pusat dari masing-masing organisasi profesi;</li>
                                        <li>Instansi-instansi yang dianggap perlu.</li>
                                    </ol>
                                </li>
                                <li>Apabila seseorang telah dipecat, maka Dewan Kehormatan Pusat atau Dewan Kehormatan Cabang/Daerah meminta kepada Dewan Pimpinan Pusat/Organisasi profesi untuk memecat orang yang bersangkutan dari keanggotaan organisasi profesi.</li>
                            </ol>


